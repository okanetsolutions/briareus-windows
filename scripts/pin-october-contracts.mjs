// Offline fixture refresh: node scripts/pin-october-contracts.mjs /path/to/briareus
// The supplied checkout must be the final merged source, never a planning head.
import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { pathToFileURL } from 'node:url';

const commit = '8079fcd341e87dba7ede9b8a9a6a534c5f8338cb';
const root = resolve(process.argv[2] || '.');
if (execFileSync('git', ['-C', root, 'rev-parse', 'HEAD'], { encoding: 'utf8' }).trim() !== commit) {
    throw new Error(`Expected core ${commit}; check out the pinned source before refreshing.`);
}
execFileSync('git', ['-C', root, 'diff', '--exit-code', 'HEAD', '--',
    'lib/api-v1-catalog.js', 'lib/api-v1-docs.js'], { stdio: 'pipe' });
const { apiV1OpenApi } = await import(pathToFileURL(resolve(root, 'lib/api-v1-docs.js')));
const document = apiV1OpenApi();
const keep = path => /^\/(settings\/(mail\/accounts|mcp\/servers)|mail|slack\/workspaces)(\/|$)/.test(path)
    || ['/pulls', '/runtimes', '/sessions', '/sessions/{id}', '/sessions/{id}/messages',
        '/sessions/{id}/cancel', '/sessions/{id}/compact', '/sessions/{id}/btw',
        '/sessions/{id}/events', '/usage/all', '/repo/archive', '/repo/tree', '/repo/file',
        '/pulls/{number}/description', '/pulls/{number}/findings'].includes(path);
// Keep protocol data; prose stays in the pinned reference linked in the evidence report.
const stripProse = value => {
    if (Array.isArray(value)) return value.map(stripProse);
    if (value && typeof value === 'object') return Object.fromEntries(Object.entries(value)
        .filter(([key]) => !['description', 'summary'].includes(key))
        .map(([key, child]) => [key, stripProse(child)]));
    return value;
};
const paths = Object.fromEntries(Object.entries(document.paths).filter(([path]) => keep(path)));
const schemas = {};
function includeReferences(value) {
    if (!value || typeof value !== 'object') return;
    if (value.$ref) {
        const name = value.$ref.replace('#/components/schemas/', '');
        if (!document.components.schemas[name]) throw new Error(`Missing schema ${name}`);
        if (!schemas[name]) {
            schemas[name] = document.components.schemas[name];
            includeReferences(schemas[name]);
        }
    }
    for (const child of Object.values(value)) includeReferences(child);
}
includeReferences(paths);
const snapshot = stripProse({
    openapi: document.openapi,
    info: document.info,
    'x-core-commit': commit,
    paths,
    components: { schemas },
});
const out = resolve('tests/fixtures/october-2026');
writeFileSync(resolve(out, 'catalog.json'), JSON.stringify(snapshot, null, 4) + '\n');
const compact = JSON.stringify(snapshot);
// Short literals work with MSVC's translation limits; tests concatenate the chunks.
const chunks = compact.match(/.{1,1000}/gu).map(chunk => `    ${JSON.stringify(chunk)},`);
writeFileSync(resolve(out, 'catalog.h'), '// Generated by scripts/pin-october-contracts.mjs; do not edit.\n'
    + 'static const char *const OCTOBER_CATALOG[] = {\n' + chunks.join('\n') + '\n};\n');
console.log(`Pinned ${Object.keys(snapshot.paths).length} paths from ${commit}`);
